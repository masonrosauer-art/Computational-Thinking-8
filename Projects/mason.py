# ###############################################
# ### SETUP ###
import turtle
# ###############################################

t = turtle.Turtle()
t.penup()
t.goto(-100, -100)
t.color("purple")
t.pendown()

t.forward(120)
t.left(45)
t.forward(130)
t.left(45)
t.forward(120)


# ###############################################
# ### ENDING ###
turtle.exitonclick()
